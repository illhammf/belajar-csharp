using System;

class Program
{
    static void Main()
    {
        int nilai = 60;

        // Jika nilai >= 75, maka lulus
        if (nilai >= 75)
        {
            Console.WriteLine("Lulus");
        }
        // Jika kondisi if salah, maka else dijalankan
        else
        {
            Console.WriteLine("Tidak lulus");
        }
    }
}