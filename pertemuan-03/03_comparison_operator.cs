// ==========================================
// Comparison Operator
// ==========================================

int angkaA = 10;
int angkaB = 5;

// ==
// Mengecek apakah kedua nilai sama
Console.WriteLine($"A == B : {angkaA == angkaB}");

// !=
// Mengecek apakah kedua nilai berbeda
Console.WriteLine($"A != B : {angkaA != angkaB}");

// >
// Mengecek apakah A lebih besar dari B
Console.WriteLine($"A > B  : {angkaA > angkaB}");

// <
// Mengecek apakah A lebih kecil dari B
Console.WriteLine($"A < B  : {angkaA < angkaB}");

// >=
// Mengecek apakah A lebih besar atau sama dengan B
Console.WriteLine($"A >= B : {angkaA >= angkaB}");

// <=
// Mengecek apakah A lebih kecil atau sama dengan B
Console.WriteLine($"A <= B : {angkaA <= angkaB}");