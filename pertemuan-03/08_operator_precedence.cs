// ==========================================
// Operator Precedence
// ==========================================

// Perkalian memiliki prioritas lebih tinggi
// daripada penjumlahan.

int hasil1 = 10 + 5 * 2;

Console.WriteLine($"Hasil 1 : {hasil1}");


// ==========================================
// Menggunakan tanda kurung
// ==========================================

// Tanda kurung memiliki prioritas lebih tinggi
// sehingga penjumlahan dilakukan terlebih dahulu.

int hasil2 = (10 + 5) * 2;

Console.WriteLine($"Hasil 2 : {hasil2}");


// Contoh lainnya
int hasil3 = 20 - 10 / 2;

Console.WriteLine($"Hasil 3 : {hasil3}");


// Dengan tanda kurung
int hasil4 = (20 - 10) / 2;

Console.WriteLine($"Hasil 4 : {hasil4}");