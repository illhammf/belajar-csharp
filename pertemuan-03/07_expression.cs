// ==========================================
// Expression
// ==========================================

int angkaA = 10;
int angkaB = 5;

// Expression:
// angkaA + angkaB
int hasilTambah = angkaA + angkaB;

Console.WriteLine($"Hasil tambah : {hasilTambah}");


// Expression dengan beberapa operator
int hasil = (angkaA + angkaB) * 2;

Console.WriteLine($"Hasil akhir  : {hasil}");


// Expression juga bisa digunakan dalam kondisi
bool lebihBesar = angkaA > angkaB;

Console.WriteLine($"A lebih besar dari B : {lebihBesar}");