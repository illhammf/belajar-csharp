// ==========================================
// Arithmetic Operator
// ==========================================

// Dua variabel untuk melakukan operasi matematika
int angkaA = 20;
int angkaB = 6;

// Penjumlahan
Console.WriteLine($"Penjumlahan : {angkaA + angkaB}");

// Pengurangan
Console.WriteLine($"Pengurangan : {angkaA - angkaB}");

// Perkalian
Console.WriteLine($"Perkalian   : {angkaA * angkaB}");

// Pembagian
Console.WriteLine($"Pembagian   : {angkaA / angkaB}");

// Modulus digunakan untuk mendapatkan sisa pembagian
Console.WriteLine($"Modulus     : {angkaA % angkaB}");