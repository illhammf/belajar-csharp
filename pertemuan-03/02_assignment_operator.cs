// ==========================================
// Assignment Operator
// ==========================================

// Assignment dasar menggunakan =
int angka = 10;

Console.WriteLine($"Nilai awal : {angka}");

// +=
// Sama seperti:
// angka = angka + 5;
angka += 5;

Console.WriteLine($"Setelah += 5 : {angka}");

// -=
// Sama seperti:
// angka = angka - 3;
angka -= 3;

Console.WriteLine($"Setelah -= 3 : {angka}");

// *=
// Sama seperti:
// angka = angka * 2;
angka *= 2;

Console.WriteLine($"Setelah *= 2 : {angka}");

// /=
// Sama seperti:
// angka = angka / 4;
angka /= 4;

Console.WriteLine($"Setelah /= 4 : {angka}");

// %=
// Sama seperti:
// angka = angka % 3;
angka %= 3;

Console.WriteLine($"Setelah %= 3 : {angka}");