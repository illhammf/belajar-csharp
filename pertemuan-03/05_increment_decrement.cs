// ==========================================
// Increment & Decrement
// ==========================================

int angka = 10;

Console.WriteLine($"Nilai awal : {angka}");

// ++ menambahkan nilai sebesar 1
angka++;

Console.WriteLine($"Setelah ++ : {angka}");

// ++ lagi
angka++;

Console.WriteLine($"Setelah ++ : {angka}");

// -- mengurangi nilai sebesar 1
angka--;

Console.WriteLine($"Setelah -- : {angka}");

// -- lagi
angka--;

Console.WriteLine($"Setelah -- : {angka}");