// String interpolation menggunakan tanda $
// untuk memasukkan variable langsung ke dalam string.

string nama = "Ilham";
int umur = 20;
string kota = "Tangerang";

// Menampilkan beberapa variable menggunakan interpolation
Console.WriteLine($"Nama : {nama}");
Console.WriteLine($"Umur : {umur}");
Console.WriteLine($"Kota : {kota}");