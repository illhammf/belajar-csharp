// Contoh beberapa data type dasar dalam C#.

// string digunakan untuk menyimpan teks
string nama = "Ilham";

// int digunakan untuk menyimpan bilangan bulat
int umur = 20;

// double digunakan untuk menyimpan bilangan desimal
double tinggi = 170.5;

// bool digunakan untuk menyimpan true atau false
bool mahasiswa = true;

// Menampilkan semua data
Console.WriteLine(nama);
Console.WriteLine(umur);
Console.WriteLine(tinggi);
Console.WriteLine(mahasiswa);